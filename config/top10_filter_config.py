# ============================================================
# 定時サマリー TOP10 用 売買代金フィルター設定
# ------------------------------------------------------------
# ✔ 数値はすべてここで一元管理
# ✔ ロジック側は一切変更しない
# ✔ 地合い・将来チューニング対応
# ✔ 通常判定 / 緩和判定（昼・閑散）を両立
# ============================================================


class Top10FilterConfig:
    """
    TOP10 売買代金フィルター設定クラス

    ・summary / ranking / AI からは
      「passes_top10_filter(cfg=cfg)」のみを呼ぶ
    ・数値調整・地合い対応はこのクラスだけで完結させる
    """

    # --------------------------------------------------------
    # 【1】1日トータル売買代金（最終的な格）
    # --------------------------------------------------------
    # 後場・引け・最終的な TOP10 表示に必要な最低ライン
    MIN_DAILY_TURNOVER = 700_000_000   # 7億円


    # --------------------------------------------------------
    # 【2】前場後半〜昼前の実績ベース（やや緩め）
    # --------------------------------------------------------
    # 10:30〜12:30 に使用
    # 寄り後に伸びたが、まだ7億未満の主役候補を残す
    MIN_MIDDAY_TURNOVER = 500_000_000  # 5億円


    # --------------------------------------------------------
    # 【3】寄り付き〜前場中盤のペース判定
    # --------------------------------------------------------
    # 現時点の累計を 1日（390分）に換算した「見込み」
    # projected_daily_turnover >= この値 なら通過
    MIN_PROJECTED_TURNOVER = 700_000_000  # 7億円ペース


    # --------------------------------------------------------
    # 【4】出来高急減フィルター（前場中盤専用）
    # --------------------------------------------------------
    # 直近5分売買代金 / 直前15分平均売買代金
    # この値を下回ったら「勢い失速」と判断
    VOLUME_DROP_RATIO = 0.5


    # --------------------------------------------------------
    # 【5】出来高急減をチェックする時間帯
    # --------------------------------------------------------
    # 09:15〜10:30 のみ適用（寄り付き直後は除外）
    VOLUME_DROP_START = (9, 15)
    VOLUME_DROP_END   = (10, 30)


    # --------------------------------------------------------
    # 【6】市場設定（将来拡張用）
    # --------------------------------------------------------
    # 日本株 1日の立会時間（分）
    MARKET_MINUTES = 390


    # --------------------------------------------------------
    # 【7】緩和（relax）モード設定（昼・閑散対策）
    # --------------------------------------------------------
    # 通常条件が全滅した場合にのみ適用される倍率
    # 例）0.5 → 売買代金条件を 50% に緩和
    RELAX_TURNOVER_RATIO = 0.5


    # --------------------------------------------------------
    # 【8】デバッグ・ログ制御
    # --------------------------------------------------------
    # True の場合：
    #   ・STEP1 / STEP2 / ALL FAILED のログを詳細出力
    #   ・将来の数値調整に使える
    ENABLE_DEBUG_LOG = True
