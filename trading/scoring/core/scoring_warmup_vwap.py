from __future__ import annotations

import numpy as np
import pandas as pd


# ============================================================
# 安全除算
# ============================================================

def _safe_div(a: pd.Series, b: pd.Series) -> pd.Series:
    """
    ゼロ除算完全防止
    """
    b_safe = b.replace(0, np.nan)
    return a / b_safe


# ============================================================
# VWAP 補正
# ============================================================

def scoring_warmup_vwap(df: pd.DataFrame) -> pd.DataFrame:

    if df is None or df.empty:
        return df

    df = df.copy()

    # --------------------------------------------------------
    # score_total 存在保証
    # --------------------------------------------------------
    if "score_total" not in df.columns:
        df["score_total"] = 0.0

    df["score_total"] = pd.to_numeric(
        df["score_total"], errors="coerce"
    ).fillna(0.0)

    # --------------------------------------------------------
    # 必須カラム確認
    # --------------------------------------------------------
    required_cols = {"close", "vwap"}

    if not required_cols.issubset(df.columns):
        return df

    # --------------------------------------------------------
    # 数値変換（完全防御）
    # --------------------------------------------------------
    close = pd.to_numeric(df["close"], errors="coerce")
    vwap = pd.to_numeric(df["vwap"], errors="coerce")

    # --------------------------------------------------------
    # 差分計算
    # --------------------------------------------------------
    diff = close - vwap

    ratio = _safe_div(diff, vwap)

    # --------------------------------------------------------
    # NaN処理
    # --------------------------------------------------------
    ratio = ratio.replace([np.inf, -np.inf], np.nan).fillna(0.0)

    # --------------------------------------------------------
    # 極端値制限（±5%まで）
    # --------------------------------------------------------
    ratio = ratio.clip(-0.05, 0.05)

    # --------------------------------------------------------
    # スコア反映（最大±2）
    # --------------------------------------------------------
    vwap_score = ratio * 40.0  # 0.05 × 40 = 2

    df["score_total"] += vwap_score

    # --------------------------------------------------------
    # 最終スコア制限（暴走防止）
    # --------------------------------------------------------
    df["score_total"] = df["score_total"].clip(-20.0, 20.0)

    # --------------------------------------------------------
    # BUY / SELL 再生成（数値保証）
    # --------------------------------------------------------
    df["score_buy"] = df["score_total"].clip(lower=0.0)
    df["score_sell"] = (-df["score_total"]).clip(lower=0.0)

    return df