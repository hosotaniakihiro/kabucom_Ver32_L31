from typing import TypedDict, Optional, Literal
import datetime as dt

# ------------------------------------------------------------
# 基本 Enum 的 Literal
# ------------------------------------------------------------
Side = Literal["BUY", "SELL"]

Source = Literal[
    "SUMMARY_AI",   # summary → AI 判定後
    "RANKING_AI",   # ranking → AI 判定後
    "SUMMARY",      # summary 直
    "RANKING",      # ranking 直
    "UNKNOWN",
]


# ------------------------------------------------------------
# pending_entries の 1 要素（最小単位）
# ------------------------------------------------------------
class PendingEntry(TypedDict, total=False):
    """
    pending_entries に格納される 1 エントリーの標準形

    ※ total=False：
      すべて必須にはしない（移行期・旧データ吸収用）
    """

    # ========================================================
    # 基本識別情報（最重要）
    # ========================================================
    symbol: str                 # 銘柄コード（文字列統一）
    side: Side                  # BUY / SELL

    # ========================================================
    # スコア系
    # ========================================================
    score: int                  # スコア（rule / summary）
    confidence: float           # AI 生 confidence（0.0〜1.0）
    weight_confidence: float    # source 重み付け後 confidence
    dominant_ratio: float       # 構造優勢度（0.0〜1.0）

    # ========================================================
    # 時間・周期
    # ========================================================
    interval: int               # 1 / 3 / 5
    datetime: Optional[dt.datetime]

    # ========================================================
    # 出所
    # ========================================================
    source: Source              # SUMMARY_AI / RANKING_AI など

    # ========================================================
    # AI 判定結果（enrich 後）
    # ========================================================
    ai_allow: bool              # AI 最終許可
    ai_reason: str              # AI 理由文字列

    # ========================================================
    # 互換・移行期用（旧構造吸収）
    # ========================================================
    entry_decision: Side        # 旧キー互換
    score_total: int            # 旧キー互換
