# ------------------------------------------------------------
# 殿様イナゴ（SELL）専用 EXIT コントローラ
#
# ✔ 秒殺・裁量ゼロ
# ✔ 下げは速い → HOLD は BUY より短く
# ✔ 踏み上げは即死 → 損切を最優先
# ✔ ENTRY ロジックと完全独立
# ============================================================

from __future__ import annotations


# ============================================================
# 固定パラメータ（絶対に変更しない）
# ============================================================

# 利確（下げは速い）
TAKE_PROFIT_HALF = 0.004   # +0.4%
TAKE_PROFIT_FULL = 0.007   # +0.7%

# 損切（踏み上げは致命傷）
STOP_LOSS = -0.003         # -0.3%

# 時間（SELL は短命）
MAX_HOLD_SECONDS = 120     # 2分

# 勢い消失（売り板圧低下）
MIN_SELL_PRESSURE = 1.2


# ============================================================
# メイン API
# ============================================================

def sell_tonosama_exit(ctx) -> None:
    """
    殿様イナゴ SELL 用 EXIT 判定

    Parameters
    ----------
    ctx : ExitContext 互換オブジェクト
        必須属性:
          - ret : float
              現在のリターン（+ 利益 / - 損失）
          - hold_seconds : int
              保持時間（秒）
          - sell_pressure : float
              現在の売り板圧
        必須メソッド:
          - exit_half()
          - exit_all()
    """

    # --------------------------------------------------------
    # safety
    # --------------------------------------------------------
    if ctx is None:
        return

    ret = float(getattr(ctx, "ret", 0.0))
    hold = int(getattr(ctx, "hold_seconds", 0))
    sell_pressure = float(getattr(ctx, "sell_pressure", 0.0))

    # --------------------------------------------------------
    # ① 即損切（最優先：踏み上げ回避）
    # --------------------------------------------------------
    if ret <= STOP_LOSS:
        ctx.exit_all()
        return

    # --------------------------------------------------------
    # ② 最大利確（取り切り）
    # --------------------------------------------------------
    if ret >= TAKE_PROFIT_FULL:
        ctx.exit_all()
        return

    # --------------------------------------------------------
    # ③ 半分利確（保険）
    # --------------------------------------------------------
    if ret >= TAKE_PROFIT_HALF:
        ctx.exit_half()
        # 半分利確後も以下を監視し続ける

    # --------------------------------------------------------
    # ④ 時間切れ（SELL は命が短い）
    # --------------------------------------------------------
    if hold >= MAX_HOLD_SECONDS:
        ctx.exit_all()
        return

    # --------------------------------------------------------
    # ⑤ 売り勢い消失
    # --------------------------------------------------------
    if sell_pressure < MIN_SELL_PRESSURE:
        ctx.exit_all()
        return

    # --------------------------------------------------------
    # ⑥ 継続（何もしない）
    # --------------------------------------------------------
    return